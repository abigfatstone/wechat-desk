import { createInterface } from "node:readline/promises";
import {
  mkdir,
  realpath,
  lstat,
  readFile,
  writeFile,
  rm,
} from "node:fs/promises";
import { join, dirname, resolve, basename } from "node:path";
import { randomUUID } from "node:crypto";
import { fileURLToPath } from "node:url";
import { scope } from "./state.mjs";
import { ilink } from "./ilink.mjs";
import qr from "./vendor/qr.cjs";
const base = dirname(fileURLToPath(import.meta.url)),
  sc = await scope(process.cwd()),
  cmd = process.argv[2] || "enable";
const adapter = join(
  sc.root,
  ".opencode",
  "plugins",
  "wechat-desk",
  "index.ts",
);
const marker = "// generated by zero-wechat-desk";
async function attach() {
  await mkdir(dirname(adapter), { recursive: true });
  if ((await realpath(dirname(adapter))) !== dirname(adapter))
    throw Error("插件安装目录不能是符号链接");
  const old = await readFile(adapter, "utf8").catch((e) => {
    if (e.code === "ENOENT") return null;
    throw e;
  });
  if (old !== null && !old.startsWith(marker + "\n"))
    throw Error("已有同名插件，未覆盖");
  const code = `${marker}\nexport {default} from ${JSON.stringify(new URL("zero.mjs", import.meta.url).href)};\n`;
  await writeFile(adapter, code, { flag: old === null ? "wx" : "w" });
}
async function detach() {
  if (
    (await readFile(adapter, "utf8").catch(() => "")).startsWith(marker + "\n")
  )
    await rm(adapter);
}
const rl = createInterface({ input: process.stdin, output: process.stdout });
async function ask(s) {
  return (await rl.question(s + " ")).trim();
}
async function main() {
  if (cmd === "status") {
    const g = await sc.load("grant"),
      b = await sc.load("binding");
    console.log(
      JSON.stringify(
        {
          workspace: sc.root,
          host: g?.host ?? null,
          history: g?.source?.kind ?? "未授权",
          clawbot:
            g?.host === "openclaw"
              ? "由 OpenClaw 渠道管理"
              : b?.disconnected
                ? "会话失效"
                : b
                  ? "本机已保存绑定"
                  : "未绑定",
          delivery: await sc.load("delivery"),
          health: await sc.load("health"),
        },
        null,
        2,
      ),
    );
    return;
  }
  if (!process.stdin.isTTY) throw Error("授权与扫码请在本机交互终端执行");
  console.log("当前 workspace：" + sc.root);
  if (cmd === "disable") {
    await sc.drop("grant");
    await detach();
    for (const key of [
      "binding",
      "sync",
      "delivery",
      "health",
      "thread",
      "pending",
      "job",
    ])
      await sc.drop(key);
    console.log("已撤销本机授权并删除本机绑定。既有零点会话仍保留。");
    return;
  }
  if (cmd === "unlock") {
    const lock = join(sc.dir, "receiver.lock");
    const pid = Number(await readFile(lock, "utf8"));
    if (!Number.isInteger(pid) || pid <= 0) throw Error("锁状态异常");
    try {
      process.kill(pid, 0);
      throw Error("接收进程仍在运行");
    } catch (e) {
      if (e.code !== "ESRCH") throw e;
    }
    await rm(lock);
    console.log("已清理失效接收锁，请重新打开 workspace");
    return;
  }
  if (cmd !== "enable")
    throw Error("用法：setup.mjs [enable|status|disable|unlock]");
  const host = (await ask("入口 [zero/openclaw]（默认 zero）：")) || "zero";
  if (!["zero", "openclaw"].includes(host)) throw Error("未知入口");
  const kind = await ask(
    "资料源：1 已经可查询的 tzwkb 本机环境；2 已导出的文件目录：",
  );
  let source;
  if (kind === "1") {
    const directory = await realpath(resolve(await ask("tzwkb 项目路径：")));
    if (!(await lstat(join(directory, "scripts/common/query.py"))).isFile())
      throw Error("未找到只读查询入口");
    // Preserve venv interpreter symlink; resolving it invalidates virtualenv discovery.
    const python = resolve(
      (await ask("已有 Python 环境解释器路径（留空使用项目 .venv）：")) ||
        join(
          directory,
          process.platform === "win32"
            ? ".venv/Scripts/python.exe"
            : ".venv/bin/python",
        ),
    );
    await realpath(python);
    source = { kind: "tzwkb", directory, python };
  } else if (kind === "2") {
    const directory = await realpath(
      resolve(await ask("专门放置聊天导出的目录：")),
    );
    if (!(await lstat(directory)).isDirectory()) throw Error("请选择目录");
    source = { kind: "archive", directory };
  } else throw Error("未知资料源");
  console.log(
    "将允许这个 workspace 查询所选资料源，命中的片段可进入当前模型上下文。",
  );
  if ((await ask("输入 YES 启用：")) !== "YES") return;
  const owner =
    host === "openclaw"
      ? await ask("官方微信渠道中允许查询的本人 sender ID：")
      : null;
  if (host === "openclaw" && !owner) throw Error("需要明确授权发送者");
  const peers = [];
  if (host === "zero")
    for (;;) {
      const name = await ask("可转发的目标 workspace 别名（回车结束）：");
      if (!name) break;
      if (!/^[^\s@]{1,40}$/u.test(name) || peers.some((p) => p.name === name))
        throw Error("别名无效或重复");
      const id = await ask("该 workspace 的零点 Agent ID（UUID）：");
      if (!/^[a-f\d]{8}(-[a-f\d]{4}){3}-[a-f\d]{12}$/i.test(id))
        throw Error("Agent ID 无效");
      peers.push({ name, id });
    }
  let binding = await sc.load("binding");
  if (
    host === "zero" &&
    (await ask(
      "在这台 workspace 绑定微信？会替换同一微信先前的入口 [y/N]：",
    )) === "y"
  ) {
    binding = await ilink().bind({
      previous: binding?.disconnected ? null : binding,
      signal: AbortSignal.timeout(8 * 60000),
      show: async (url) => {
        console.log("请用微信扫描本机二维码：");
        qr.generate(url, { small: true });
      },
      pin: () => ask("请在本机输入微信显示的数字："),
    });
    await sc.save("binding", binding);
  }
  if (host === "openclaw") {
    await detach();
    await sc.drop("binding");
    await sc.drop("sync");
  }
  const catalog =
    host === "zero" && basename(dirname(base)) === "zero-plugins"
      ? join(dirname(base), "installed.json")
      : null;
  await sc.save("grant", {
    id: randomUUID(),
    root: sc.root,
    host,
    owner,
    source,
    catalog,
    peers,
  });
  await sc.drop("health");
  if (host === "zero") {
    await attach();
    console.log("已授权。打开或重新加载这个 workspace；直接询问微信历史。");
  } else
    console.log(
      "已授权。请在 OpenClaw 安装本插件，并将官方微信渠道配置为本人私聊。",
    );
}
try {
  await main();
} catch (e) {
  console.error("未完成：" + e.message);
  process.exitCode = 1;
} finally {
  rl.close();
}
