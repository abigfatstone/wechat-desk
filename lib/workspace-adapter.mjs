import { mkdir, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { DeskError } from "./errors.mjs";

const MARKER = "// generated by wechat-desk";
const REL = join(".opencode", "plugins", "wechat-desk", "index.ts");

// opencode loads every module under <workspace>/.opencode/plugins at startup.
// Writing this one-line adapter is what makes the plugin resident: no daemon,
// no launchd, no plist — the host that has the model is the host that runs it.
export async function installAdapter({ workspace, entry }) {
  const adapter = join(workspace, REL);
  await mkdir(dirname(adapter), { recursive: true });

  const existing = await readFile(adapter, "utf8").catch((err) => {
    if (err.code === "ENOENT") return null;
    throw err;
  });
  if (existing !== null && !existing.startsWith(MARKER)) {
    throw new DeskError("IO_ERROR", { reason: "adapter exists", adapter });
  }

  const code = `${MARKER}\nexport { default } from ${JSON.stringify(entry)};\n`;
  await writeFile(adapter, code, "utf8");
  return { adapter };
}

export async function removeAdapter({ workspace }) {
  const adapter = join(workspace, REL);
  const existing = await readFile(adapter, "utf8").catch(() => null);
  if (existing === null) return { removed: false };
  if (!existing.startsWith(MARKER)) {
    throw new DeskError("IO_ERROR", { reason: "adapter not ours", adapter });
  }
  await rm(adapter, { force: true });
  return { removed: true };
}

export async function adapterInstalled({ workspace }) {
  const adapter = join(workspace, REL);
  const existing = await readFile(adapter, "utf8").catch(() => null);
  return existing !== null && existing.startsWith(MARKER);
}

export async function workspaceRoot(workspace) {
  return await realpath(workspace).catch(() => {
    throw new DeskError("BAD_ARGS", { reason: "workspace", workspace });
  });
}
