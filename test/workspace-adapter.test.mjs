import test from "node:test";
import assert from "node:assert/strict";
import { mkdir, readFile, writeFile, stat } from "node:fs/promises";
import { join } from "node:path";
import { adapterInstalled, installAdapter, removeAdapter } from "../lib/workspace-adapter.mjs";
import { makeTemp } from "./helpers.mjs";

const ENTRY = "file:///repo/plugins/wechat-desk/zero.mjs";

test("写入适配器并指向插件入口", async () => {
  const ws = await makeTemp("desk-ws-");
  const { adapter } = await installAdapter({ workspace: ws, entry: ENTRY });
  const code = await readFile(adapter, "utf8");
  assert.match(code, /generated by wechat-desk/);
  assert.match(code, /export \{ default \} from "file:\/\/\/repo\/plugins\/wechat-desk\/zero\.mjs"/);
  assert.equal(await adapterInstalled({ workspace: ws }), true);
});

test("重复安装是幂等的", async () => {
  const ws = await makeTemp("desk-ws-");
  await installAdapter({ workspace: ws, entry: ENTRY });
  await installAdapter({ workspace: ws, entry: ENTRY });
  const code = await readFile(join(ws, ".opencode/plugins/wechat-desk/index.ts"), "utf8");
  assert.equal(code.match(/generated by wechat-desk/g).length, 1);
});

test("不覆盖别人的适配文件", async () => {
  const ws = await makeTemp("desk-ws-");
  const adapter = join(ws, ".opencode/plugins/wechat-desk/index.ts");
  await mkdir(join(ws, ".opencode/plugins/wechat-desk"), { recursive: true });
  await writeFile(adapter, "// someone else's plugin\n");
  await assert.rejects(
    () => installAdapter({ workspace: ws, entry: ENTRY }),
    (err) => err.code === "IO_ERROR",
  );
  assert.equal(await readFile(adapter, "utf8"), "// someone else's plugin\n");
});

test("卸载只删自己的适配器", async () => {
  const ws = await makeTemp("desk-ws-");
  await installAdapter({ workspace: ws, entry: ENTRY });
  assert.deepEqual(await removeAdapter({ workspace: ws }), { removed: true });
  await assert.rejects(() => stat(join(ws, ".opencode/plugins/wechat-desk/index.ts")), (e) => e.code === "ENOENT");
  assert.equal(await adapterInstalled({ workspace: ws }), false);
});

test("没有适配器时卸载是空操作", async () => {
  const ws = await makeTemp("desk-ws-");
  assert.deepEqual(await removeAdapter({ workspace: ws }), { removed: false });
});
